from techshort.domain.creative import Beat, BeatPlan, NarrativeBrief, derive_creative_id


def _beat(
    order: int,
    role: str,
    purpose: str,
    narration: str,
    text: str,
    visual: str,
    primitive: str,
    layout: str,
    animation: list[str],
    claims: list[str],
    seconds: float,
    evidence: list[str] | None = None,
) -> Beat:
    return Beat.model_validate(
        {
            "beat_id": f"beat-{order + 1:02d}",
            "order": order,
            "role": role,
            "purpose": purpose,
            "narration_guidance": narration,
            "on_screen_text": text,
            "visual_guidance": visual,
            "primitive_hint": primitive,
            "layout_family": layout,
            "animation_beats": animation,
            "claim_ids": claims,
            "evidence_span_ids": evidence or [],
            "approximate_duration": seconds,
        }
    )


