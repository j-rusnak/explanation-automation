def build_rolling_shutter_beat_plan(brief: NarrativeBrief) -> BeatPlan:
    """Return a complete editorial spine whose order changes with the selected angle."""
    if brief.angle == "surprising-result":
        beats = _surprising_result_beats()
    elif brief.angle == "everyday-mechanism":
        beats = _everyday_mechanism_beats()
    else:
        beats = _engineering_tradeoff_beats()
    payload: dict[str, object] = {
        "narrative_brief_version_id": brief.version_id,
        "claims_version_id": brief.claims_version_id,
        "angle": brief.angle,
        "factual_locks": brief.factual_locks,
        "beats": beats,
    }
    payload["version_id"] = derive_creative_id("beats", payload)
    return BeatPlan.model_validate(payload)
